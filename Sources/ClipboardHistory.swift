struct HistoryView: View {
    @ObservedObject var store: ClipStore
    @ObservedObject var panel: Panel
    @ObservedObject var settings: Settings
    var onPick: (ClipItem) -> Void
    var onCopyAll: ([ClipItem]) -> Void
    var onClear: () -> Void
    @FocusState private var searchFocused: Bool

    var body: some View {
        let visible = panel.visible
        VStack(spacing: 0) {
            HStack(spacing: 6) {
                Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                TextField("Search clipboard history", text: $panel.query)
                    .textFieldStyle(.plain)
                    .focused($searchFocused)
                if !panel.query.isEmpty {
                    Button { panel.query = "" } label: { Image(systemName: "xmark.circle.fill") }
                        .buttonStyle(.plain).foregroundStyle(.secondary)
                }
                Button { onCopyAll(visible) } label: {
                    Label(panel.query.isEmpty ? "Copy All" : "Copy \(visible.count)", systemImage: "doc.on.doc")
                        .font(.caption)
                }
                .buttonStyle(.bordered).controlSize(.small)
                .disabled(visible.isEmpty)
                .help(panel.query.isEmpty ? "Copy every item (⇧⌘C)" : "Copy the matching items (⇧⌘C)")
            }
            .padding(.horizontal, 12).padding(.vertical, 10)

            Divider()

            if visible.isEmpty {
                VStack(spacing: 8) {
                    Image(systemName: store.items.isEmpty ? "doc.on.clipboard" : "magnifyingglass")
                        .font(.system(size: 28)).foregroundStyle(.tertiary)
                    Text(store.items.isEmpty ? "Copy something and it will show up here." : "No matches")
                        .foregroundStyle(.secondary)
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 2) {
                            let pinnedCount = visible.filter(\.pinned).count
                            ForEach(Array(visible.enumerated()), id: \.element.id) { index, item in
                                if pinnedCount > 0 && (index == 0 || index == pinnedCount) {
                                    Text(index == 0 ? "Pinned" : "Recent")
                                        .font(.caption.weight(.semibold)).foregroundStyle(.secondary)
                                        .frame(maxWidth: .infinity, alignment: .leading)
                                        .padding(.horizontal, 8).padding(.top, index == 0 ? 2 : 8)
                                }
                                ClipRow(item: item, index: index, store: store, isSelected: index == panel.selected,
                                        now: panel.now, onCopy: { onPick(item) })
                                    .id(item.id)
                                    .onTapGesture { onPick(item) }
                                    .onHover { if $0 { panel.selected = index } }
                            }
                        }
                        .padding(6)
                    }
                    .onChange(of: panel.selected) { _, new in
                        if visible.indices.contains(new) { proxy.scrollTo(visible[new].id) }
                    }
                }
            }

            Divider()

            HStack {
                Text("\(store.unpinnedCount) of \(store.limit)")
                    .font(.caption).foregroundStyle(.secondary)
                if store.paused {
                    Label("Paused", systemImage: "pause.circle.fill")
                        .font(.caption).foregroundStyle(.orange)
                }
                Spacer()
                Text("↩ paste  ⌘1–9 quick pick")
                    .font(.caption2).foregroundStyle(.tertiary)
                Menu {
                    Picker("Keep last", selection: $store.limit) {
                        ForEach(ClipStore.limits, id: \.self) { Text("\($0) items").tag($0) }
                    }
                    Toggle("Paste automatically after picking", isOn: $settings.autoPaste)
                    Toggle("Launch at login", isOn: $settings.launchAtLogin)
                    Toggle("Pause recording", isOn: $store.paused)
                    Divider()
                    Button("Clear history (keeps pinned)…", action: onClear)
                    Divider()
                    Button("Quit Clipboard History") { NSApp.terminate(nil) }
                } label: {
                    Image(systemName: "gearshape")
                }
                .menuStyle(.borderlessButton)
                .menuIndicator(.hidden)
                .fixedSize()
            }
            .padding(.horizontal, 12).padding(.vertical, 8)
        }
        .frame(width: 380, height: 480)
        .onAppear { searchFocused = true }
    }
}

struct ClipRow: View {
    let item: ClipItem
    let index: Int
    @ObservedObject var store: ClipStore
    let isSelected: Bool
    let now: Date
    var onCopy: () -> Void
    @State private var hovering = false

    private static let dayFormat: DateFormatter = {
        let f = DateFormatter()
        f.dateFormat = "d MMM, h:mm a"
        return f
    }()

    /// Always rounds down, so an older item never shows a smaller time than a newer one.
    static func ago(_ date: Date, now: Date) -> String {
        let secs = max(0, Int(now.timeIntervalSince(date)))
        switch secs {
        case ..<10: return "just now"
        case ..<60: return "\(secs) sec ago"
        case ..<3600: return "\(secs / 60) min ago"
        case ..<86400: return "\(secs / 3600) hr ago"
        default: return dayFormat.string(from: date)
        }
    }

    var body: some View {
        HStack(alignment: .center, spacing: 10) {
            preview
            Spacer(minLength: 4)
            if hovering {
                Button(action: onCopy) { Image(systemName: "doc.on.doc") }
                    .buttonStyle(.borderless).help("Copy")
                Button { store.togglePin(item) } label: {
                    Image(systemName: item.pinned ? "pin.slash" : "pin")
                }
                .buttonStyle(.borderless).help(item.pinned ? "Unpin" : "Pin")
                Button { store.delete(item) } label: { Image(systemName: "trash") }
                    .buttonStyle(.borderless).help("Delete")
            } else {
                VStack(alignment: .trailing, spacing: 2) {
                    if index < 9 {
                        Text("⌘\(index + 1)").font(.caption2.monospaced()).foregroundStyle(.tertiary)
                    }
                    HStack(spacing: 3) {
                        if item.pinned { Image(systemName: "pin.fill").font(.caption2).foregroundStyle(.orange) }
                        Text(Self.ago(item.date, now: now))
                            .font(.caption2).foregroundStyle(.secondary)
                    }
                }
            }
        }
        .padding(.horizontal, 8).padding(.vertical, 7)
        .background(
            RoundedRectangle(cornerRadius: 6)
                .fill(isSelected ? Color.accentColor.opacity(0.18) : Color.clear)
        )
        .contentShape(Rectangle())
        .onHover { hovering = $0 }
    }

    @ViewBuilder private var preview: some View {
        switch item.kind {
        case .text:
            Text(collapsed(item.text ?? ""))
                .font(.system(size: 12.5))
                .lineLimit(2)
                .truncationMode(.tail)
                .frame(maxWidth: .infinity, alignment: .leading)
        case .image:
            HStack(spacing: 8) {
                if let img = store.image(for: item) {
                    // Size the frame to the image itself so it sits flush left, in line with text rows.
                    let fit = min(120 / max(img.size.width, 1), 48 / max(img.size.height, 1))
                    Image(nsImage: img).resizable().aspectRatio(contentMode: .fit)
                        .frame(width: max(img.size.width * fit, 12), height: max(img.size.height * fit, 12))
                        .clipShape(RoundedRectangle(cornerRadius: 4))
                        .overlay(RoundedRectangle(cornerRadius: 4).strokeBorder(.quaternary))
                    Text("\(Int(img.size.width))×\(Int(img.size.height))")
                        .font(.caption).foregroundStyle(.secondary)
                } else {
                    Label("Image", systemImage: "photo").foregroundStyle(.secondary)
                }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    private func collapsed(_ s: String) -> String {
        s.split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
            .joined(separator: " ↵ ")
    }
}

// MARK: - Global hot key (⌃⌘V), no Accessibility permission needed

final class HotKey {
    private var ref: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private let action: () -> Void

    init(keyCode: Int, modifiers: Int, action: @escaping () -> Void) {
        self.action = action
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        let me = Unmanaged.passUnretained(self).toOpaque()
        InstallEventHandler(GetApplicationEventTarget(), { _, _, user in
            guard let user else { return noErr }
            let hk = Unmanaged<HotKey>.fromOpaque(user).takeUnretainedValue()
            DispatchQueue.main.async { hk.action() }
            return noErr
        }, 1, &spec, me, &handler)
        let id = EventHotKeyID(signature: OSType(0x434C_4950), id: 1) // 'CLIP'
        RegisterEventHotKey(UInt32(keyCode), UInt32(modifiers), id, GetApplicationEventTarget(), 0, &ref)
    }

    deinit {
        if let ref { UnregisterEventHotKey(ref) }
        if let handler { RemoveEventHandler(handler) }
    }
}

// MARK: - Menu bar icon

/// The full-colour app icon, cropped to its rounded tile so it fills the menu bar slot.
func statusIcon() -> NSImage {
    let size = NSSize(width: 18, height: 18)
    guard let url = Bundle.main.url(forResource: "AppIcon", withExtension: "icns"),
          let icon = NSImage(contentsOf: url) else {
        return NSImage(systemSymbolName: "list.clipboard", accessibilityDescription: nil) ?? NSImage(size: size)
    }
    return NSImage(size: size, flipped: false) { rect in
        // The tile spans 100…924 of the 1024-point icon canvas.
        let s = icon.size.width / 1024
        let tile = NSRect(x: 100 * s, y: 100 * s, width: 824 * s, height: 824 * s)
        icon.draw(in: rect, from: tile, operation: .sourceOver, fraction: 1)
        return true
    }
}

// MARK: - App delegate (status bar item + popover)

@MainActor
final class AppDelegate: NSObject, NSApplicationDelegate {
    private var statusItem: NSStatusItem!
    private let popover = NSPopover()
    private let store = ClipStore()
    private let settings = Settings()
    private lazy var panel = Panel(store: store)
    private var hotKey: HotKey?
    private var keyMonitor: Any?

    func applicationDidFinishLaunching(_ notification: Notification) {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        if let button = statusItem.button {
            button.image = statusIcon()
            button.setAccessibilityLabel("Clipboard History")
            button.action = #selector(statusClicked(_:))
            button.target = self
            button.sendAction(on: [.leftMouseUp, .rightMouseUp])
        }

        popover.behavior = .transient
        popover.animates = false
        let host = NSHostingController(rootView: HistoryView(
            store: store, panel: panel, settings: settings,
            onPick: { [weak self] in self?.pick($0) },
            onCopyAll: { [weak self] in self?.copyAll($0) },
            onClear: { [weak self] in self?.confirmClear() }
        ))
        // Fixed size: if SwiftUI resizes the popover after it opens, it grows upward behind the menu bar.
        host.sizingOptions = []
        host.view.frame = NSRect(x: 0, y: 0, width: 380, height: 480)
        popover.contentViewController = host
        popover.contentSize = NSSize(width: 380, height: 480)

        hotKey = HotKey(keyCode: kVK_ANSI_V, modifiers: controlKey | cmdKey) { [weak self] in
            MainActor.assumeIsolated { self?.togglePopover() }
        }

        store.onRecord = { [weak self] in self?.pulseIcon() }

        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            guard let self, self.popover.isShown else { return event }
            return self.handleKey(event) ? nil : event
        }
    }

    /// Brief dip-and-return of the menu bar icon to show a copy was saved.
    private func pulseIcon() {
        guard let button = statusItem.button else { return }
        button.alphaValue = 0.25
        NSAnimationContext.runAnimationGroup { ctx in
            ctx.duration = 0.45
            button.animator().alphaValue = 1
        }
    }

    @objc private func statusClicked(_ sender: NSStatusBarButton) {
        if NSApp.currentEvent?.type == .rightMouseUp {
            showContextMenu()
        } else {
            togglePopover()
        }
    }

    private func togglePopover() {
        if popover.isShown {
            popover.performClose(nil)
            return
        }
        guard let button = statusItem.button else { return }
        panel.reset()
        NSApp.activate(ignoringOtherApps: true)
        popover.show(relativeTo: button.bounds, of: button, preferredEdge: .minY)
        popover.contentViewController?.view.window?.makeKey()
    }

    private func showContextMenu() {
        let menu = NSMenu()
        let pause = NSMenuItem(title: store.paused ? "Resume Recording" : "Pause Recording",
                               action: #selector(togglePause), keyEquivalent: "")
        pause.target = self
        menu.addItem(pause)
        let clear = NSMenuItem(title: "Clear History…", action: #selector(clearFromMenu), keyEquivalent: "")
        clear.target = self
        menu.addItem(clear)
        menu.addItem(.separator())
        menu.addItem(NSMenuItem(title: "Quit Clipboard History", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q"))
        statusItem.menu = menu
        statusItem.button?.performClick(nil)
        statusItem.menu = nil
    }

    @objc private func togglePause() { store.paused.toggle() }
    @objc private func clearFromMenu() { confirmClear() }

    private func handleKey(_ event: NSEvent) -> Bool {
        let cmd = event.modifierFlags.contains(.command)
        switch Int(event.keyCode) {
        case kVK_DownArrow: panel.move(1); return true
        case kVK_UpArrow: panel.move(-1); return true
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if let item = panel.selectedItem { pick(item) }
            return true
        case kVK_Escape: popover.performClose(nil); return true
        case kVK_Delete where cmd:
            if let item = panel.selectedItem { store.delete(item); panel.move(0) }
            return true
        case kVK_ANSI_C where cmd && event.modifierFlags.contains(.shift):
            copyAll(panel.visible)
            return true
        case kVK_ANSI_P where cmd:
            if let item = panel.selectedItem { store.togglePin(item) }
            return true
        default:
            if cmd, let c = event.charactersIgnoringModifiers, let n = Int(c), (1...9).contains(n) {
                let v = panel.visible
                if v.indices.contains(n - 1) { pick(v[n - 1]) }
                return true
            }
            return false
        }
    }

    private func copyAll(_ list: [ClipItem]) {
        store.copyAll(list)
        popover.performClose(nil)
        NSApp.hide(nil)
        pulseIcon()
    }

    private func pick(_ item: ClipItem) {
        store.copy(item)
        popover.performClose(nil)
        NSApp.hide(nil) // hand focus back to the app the user was in
        guard settings.autoPaste, AXIsProcessTrusted() else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let src = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
            let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }

    private func confirmClear() {
        popover.performClose(nil)
        NSApp.activate(ignoringOtherApps: true)
        let alert = NSAlert()
        alert.messageText = "Clear clipboard history?"
        alert.informativeText = "This removes \(store.unpinnedCount) items. Pinned items are kept. This can't be undone."
        alert.addButton(withTitle: "Clear")
        alert.addButton(withTitle: "Cancel")
        alert.buttons.first?.hasDestructiveAction = true
        if alert.runModal() == .alertFirstButtonReturn { store.clearUnpinned() }
    }
}

// MARK: - Entry point

@main
enum ClipboardHistoryApp {
