// MARK: - Model

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image }
    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var date: Date
    var pinned = false
}

// MARK: - Store (watches the pasteboard, keeps history on disk)

@MainActor
final class ClipStore: ObservableObject {
    static let limits = [50, 100, 200, 500, 1000]

    @Published private(set) var items: [ClipItem] = []
    @Published var paused = false
    @Published var limit: Int {
        didSet { UserDefaults.standard.set(limit, forKey: "historyLimit"); trim(); save() }
    }

    private let pb = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    private let dir: URL
    private var fileURL: URL { dir.appendingPathComponent("history.json") }
    private var imagesDir: URL { dir.appendingPathComponent("images", isDirectory: true) }
    private let thumbs = NSCache<NSString, NSImage>()
    /// Called whenever a new copy is saved.
    var onRecord: (() -> Void)?

    // Password managers and similar apps mark secrets with these types.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        dir = base.appendingPathComponent("ClipboardHistory", isDirectory: true)
        let saved = UserDefaults.standard.integer(forKey: "historyLimit")
        limit = saved > 0 ? saved : 200
        lastChange = pb.changeCount
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        load()
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    var unpinnedCount: Int { items.filter { !$0.pinned }.count }

    private func poll() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if paused { return }
        let types = pb.types ?? []
        if types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }

        if let s = pb.string(forType: .string),
           !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            addText(s)
            onRecord?()
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff),
                  let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
            addImage(png)
            onRecord?()
        }
    }

    private func addText(_ s: String) {
        if let i = items.firstIndex(where: { $0.kind == .text && $0.text == s }) {
            var existing = items.remove(at: i)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(ClipItem(kind: .text, text: s, date: Date()), at: 0)
        }
        trim(); save()
    }

    private func addImage(_ png: Data) {
        let name = String(SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined().prefix(32)) + ".png"
        if let i = items.firstIndex(where: { $0.imageFile == name }) {
            var existing = items.remove(at: i)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            try? png.write(to: imagesDir.appendingPathComponent(name))
            items.insert(ClipItem(kind: .image, imageFile: name, date: Date()), at: 0)
        }
        trim(); save()
    }

    /// Puts an item back on the clipboard. It keeps its original time and place in the list.
    func copy(_ item: ClipItem) {
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text ?? "", forType: .string)
        case .image: if let img = image(for: item) { pb.writeObjects([img]) }
        }
        lastChange = pb.changeCount // don't record the pick as a new copy
    }

    /// Copies several items at once: all text joined by new lines, plus any images as extra clipboard items.
    func copyAll(_ list: [ClipItem]) {
        guard !list.isEmpty else { return }
        let text = list.compactMap { $0.kind == .text ? $0.text : nil }.joined(separator: "\n")
        var objects: [NSPasteboardWriting] = []
        if !text.isEmpty { objects.append(text as NSString) }
        objects += list.compactMap { $0.kind == .image ? image(for: $0) : nil }
        pb.clearContents()
        pb.writeObjects(objects)
        lastChange = pb.changeCount // don't record the combined copy as a new history item
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        trim(); save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeFileIfUnused(item)
        save()
    }

    func clearUnpinned() {
        let removed = items.filter { !$0.pinned }
        items.removeAll { !$0.pinned }
        removed.forEach(removeFileIfUnused)
        save()
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = thumbs.object(forKey: name as NSString) { return cached }
        guard let img = NSImage(contentsOf: imagesDir.appendingPathComponent(name)) else { return nil }
        thumbs.setObject(img, forKey: name as NSString)
        return img
    }

    /// Pinned items never count against the limit; the oldest unpinned ones drop off.
    private func trim() {
        var unpinnedSeen = 0
        var kept: [ClipItem] = []
        var dropped: [ClipItem] = []
        for item in items {
            if item.pinned { kept.append(item); continue }
            unpinnedSeen += 1
            if unpinnedSeen <= limit { kept.append(item) } else { dropped.append(item) }
        }
        guard !dropped.isEmpty else { return }
        items = kept
        dropped.forEach(removeFileIfUnused)
    }

    private func removeFileIfUnused(_ item: ClipItem) {
        guard let name = item.imageFile, !items.contains(where: { $0.imageFile == name }) else { return }
        try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(name))
        thumbs.removeObject(forKey: name as NSString)
    }

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: fileURL, options: .atomic)
    }
}

// MARK: - Settings

@MainActor
final class Settings: ObservableObject {
    @Published var launchAtLogin: Bool {
        didSet {
            guard launchAtLogin != (SMAppService.mainApp.status == .enabled) else { return }
            do {
                if launchAtLogin { try SMAppService.mainApp.register() } else { try SMAppService.mainApp.unregister() }
            } catch {
                NSLog("Launch at login failed: \(error)")
            }
        }
    }
    @Published var autoPaste: Bool {
        didSet {
            UserDefaults.standard.set(autoPaste, forKey: "autoPaste")
            if autoPaste { Settings.requestAccessibility() }
        }
    }

    init() {
        launchAtLogin = SMAppService.mainApp.status == .enabled
        autoPaste = UserDefaults.standard.bool(forKey: "autoPaste")
        // Turn on launch at login the first time the app runs, so history keeps recording after a restart.
        if !UserDefaults.standard.bool(forKey: "didFirstLaunch") {
            UserDefaults.standard.set(true, forKey: "didFirstLaunch")
            try? SMAppService.mainApp.register()
            launchAtLogin = SMAppService.mainApp.status == .enabled
        }
    }

    static func requestAccessibility() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }
}

// MARK: - Panel state (search + keyboard selection)

@MainActor
final class Panel: ObservableObject {
    @Published var query = "" { didSet { selected = 0 } }
    @Published var selected = 0
    /// One clock for every row, so all "… ago" labels are worked out from the same moment.
    @Published private(set) var now = Date()
    let store: ClipStore
    private var clock: Timer?

    init(store: ClipStore) {
        self.store = store
        clock = Timer.scheduledTimer(withTimeInterval: 10, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.now = Date() }
        }
    }

    /// Pinned items first, then everything else — each group strictly newest first.
    var visible: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        let matched = (q.isEmpty ? store.items : store.items.filter { ($0.text ?? "").lowercased().contains(q) })
            .sorted { $0.date > $1.date }
        return matched.filter(\.pinned) + matched.filter { !$0.pinned }
    }

    var selectedItem: ClipItem? {
        let v = visible
        return v.indices.contains(selected) ? v[selected] : nil
    }

    func move(_ delta: Int) {
        let count = visible.count
        guard count > 0 else { return }
        selected = max(0, min(count - 1, selected + delta))
    }

    func reset() { query = ""; selected = 0; now = Date() }
}

